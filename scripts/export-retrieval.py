"""Export retrieval wire contracts and labelled authored browser data; never gold data."""

import argparse
import json
import runpy
from collections.abc import Callable
from pathlib import Path
from typing import cast

from regintel.contracts.models import ResponseMeta, SuccessEnvelope
from regintel.fixtures.sources import fixture_id
from regintel.publication.models import PublishedObservation
from regintel.reads.models import ViewInfo
from regintel.retrieval.models import (
    AnswerResult,
    Citation,
    ExtractiveClaim,
    Filters,
    RetrievalHit,
    RetrievalResult,
    RetrievalWire,
    Trace,
)
from regintel.retrieval.service import current_configuration

ROOT = Path(__file__).resolve().parents[1]


def fixtures() -> bytes:
    generate = cast(
        Callable[[], bytes],
        runpy.run_path(str(ROOT / "scripts/generate-read-fixtures.py"))["artifact"],
    )
    original = json.loads(generate())
    observation = PublishedObservation.model_validate(
        original["facts"]["data"]["facts"][0]["observation"]
    )
    view = ViewInfo.model_validate_json(json.dumps(original["info"]["data"]))
    citation = Citation(
        observation_id=observation.id,
        filing_version_id=observation.filing_version_id,
        parse_version_id=observation.parse_version_id,
        source_sha256=original["evidence"]["data"]["evidence"]["source_sha256"],
        page_index=0,
        span=observation.supports[0],
        role="DISCLOSURE",
    )
    trace = Trace(
        run_id=fixture_id(780),
        configuration_sha256=current_configuration().sha256,
        question_sha256="d" * 64,
        embedding_manifest_sha256="e" * 64,
        arm="B3",
        metadata_filters_applied=True,
        filters=Filters(),
        top_k=5,
        context_budget=2048,
        context_tokens=800,
        budget_omitted=0,
        query_tokens=25,
        graph_hops=1,
        duration_ms=12.5,
    )
    result = RetrievalResult(
        view=view,
        state="AVAILABLE",
        hits=(
            RetrievalHit(
                chunk_id=fixture_id(781),
                observation=observation,
                dense_rank=1,
                lexical_rank=1,
                graph_hop=None,
                citations=(citation,),
                context_tokens=800,
            ),
        ),
        trace=trace,
    )
    answer = AnswerResult(
        retrieval=result,
        state="EXTRACTIVE_EVIDENCE",
        claims=(
            ExtractiveClaim(
                text=observation.raw_text, observation_id=observation.id, citations=(citation,)
            ),
        ),
        explanation="Verbatim published source excerpt from an authored engineering fixture.",
    )
    meta = ResponseMeta.model_validate(original["info"]["meta"])
    payload = {
        "description": "Authored retrieval/browser fixture. Not a real filing or research result.",
        "answer": SuccessEnvelope(data=answer, meta=meta).model_dump(mode="json"),
        "retrieval": SuccessEnvelope(data=result, meta=meta).model_dump(mode="json"),
    }
    return (json.dumps(payload, indent=2, sort_keys=True) + "\n").encode()


def artifacts() -> dict[Path, bytes]:
    helpers = runpy.run_path(str(ROOT / "scripts/export-contracts.py"))
    emit = cast(Callable[[dict[str, object]], str], helpers["ts_type"])
    clean = cast(Callable[[object], None], helpers["remove_openapi_annotations"])
    schema = RetrievalWire.model_json_schema(mode="serialization")
    clean(schema)
    schema["$id"] = "https://regintel.local/retrieval/1.0.0"
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    lines = [
        "// Generated by scripts/export-retrieval.py; edit the Python retrieval models.",
        "import type { CanonicalId, DecimalString, DateString } from '../contracts/generated'",
    ]
    for name in sorted(schema["$defs"]):
        lines.append(f"export type {name} = {emit(schema['$defs'][name])};")
    folder = ROOT / "frontend/src/retrieval"
    return {
        folder / "schema.json": (json.dumps(schema, indent=2, sort_keys=True) + "\n").encode(),
        folder / "generated.ts": ("\n".join(lines) + "\n").encode(),
        folder / "fixtures.generated.json": fixtures(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    for path, content in artifacts().items():
        if options.check:
            if not path.is_file() or path.read_bytes() != content:
                print("Retrieval artifact differs; run scripts/export-retrieval.py.")
                return 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(
        "Retrieval contracts/authored fixtures match."
        if options.check
        else "Retrieval contracts/authored fixtures generated."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
