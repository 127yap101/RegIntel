"""Generate the independent M3/M4 wire schema and strict TypeScript declarations."""

import argparse
import json
import runpy
from collections.abc import Callable
from pathlib import Path
from typing import cast

from regintel.module_contracts import ModuleWire

ROOT = Path(__file__).resolve().parents[1]


def artifacts() -> dict[Path, bytes]:
    helpers = runpy.run_path(str(ROOT / "scripts/export-contracts.py"))
    emit = cast(Callable[[dict[str, object]], str], helpers["ts_type"])
    clean = cast(Callable[[object], None], helpers["remove_openapi_annotations"])
    schema = ModuleWire.model_json_schema(mode="serialization")
    clean(schema)
    schema["$id"] = "https://regintel.local/learning-portfolio/1.0.0"
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    lines = [
        "// Generated by scripts/export-learning-portfolio.py; edit the Python module models.",
        "import type { CanonicalId, DecimalString, DateString } from '../contracts/generated'",
    ]
    for name in sorted(schema["$defs"]):
        lines.append(f"export type {name} = {emit(schema['$defs'][name])};")
    lines.append(f"export type ModuleWire = {emit(schema)};")
    return {
        ROOT / "frontend/src/modules/schema.json": (
            json.dumps(schema, indent=2, sort_keys=True) + "\n"
        ).encode(),
        ROOT / "frontend/src/modules/generated.ts": ("\n".join(lines) + "\n").encode(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    for path, contents in artifacts().items():
        if options.check:
            if not path.is_file() or path.read_bytes() != contents:
                print(
                    "Learning/portfolio contracts differ; run scripts/export-learning-portfolio.py."
                )
                return 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)
    print(
        "Learning/portfolio contracts match."
        if options.check
        else "Learning/portfolio contracts generated."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
