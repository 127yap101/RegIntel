"""Generate read-only consumer schemas/types without changing frozen M0 contracts."""

import argparse
import json
import runpy
from collections.abc import Callable
from pathlib import Path
from typing import cast

from regintel.reads.models import ReadWire

ROOT = Path(__file__).resolve().parents[1]


def artifacts() -> dict[Path, bytes]:
    helpers = runpy.run_path(str(ROOT / "scripts/export-contracts.py"))
    emit = cast(Callable[[dict[str, object]], str], helpers["ts_type"])
    clean = cast(Callable[[object], None], helpers["remove_openapi_annotations"])
    # These are output DTOs only. PackageVersion has a narrower serialized
    # package-name type; validate the actual wire output, never internal inputs.
    schema = ReadWire.model_json_schema(mode="serialization")
    clean(schema)
    schema["$id"] = "https://regintel.local/published-reads/1.0.0"
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    definitions = schema["$defs"]
    lines = [
        "// Generated by scripts/export-published-reads.py; edit the Python read models.",
        "import type { CanonicalId, DecimalString, DateString } from '../contracts/generated'",
    ]
    for name in sorted(definitions):
        lines.append(f"export type {name} = {emit(definitions[name])};")
    return {
        ROOT / "frontend/src/published/schema.json": (
            json.dumps(schema, indent=2, sort_keys=True) + "\n"
        ).encode(),
        ROOT / "frontend/src/published/generated.ts": ("\n".join(lines) + "\n").encode(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    for path, content in artifacts().items():
        if options.check:
            if not path.is_file() or path.read_bytes() != content:
                print("Published read artifact differs; run scripts/export-published-reads.py.")
                return 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(
        "Published read schemas/types match."
        if options.check
        else "Published read schemas/types generated."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
