"""Generate M2 consumer schema/types without changing frozen M1 contracts."""

import argparse
import json
import runpy
from collections.abc import Callable
from pathlib import Path
from typing import cast

from regintel.analysis.models import AnalysisWire

ROOT = Path(__file__).resolve().parents[1]


def artifacts() -> dict[Path, bytes]:
    helpers = runpy.run_path(str(ROOT / "scripts/export-contracts.py"))
    emit = cast(Callable[[dict[str, object]], str], helpers["ts_type"])
    clean = cast(Callable[[object], None], helpers["remove_openapi_annotations"])
    schema = AnalysisWire.model_json_schema(mode="serialization")
    clean(schema)
    schema["$id"] = "https://regintel.local/analysis/1.0.0"
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    lines = [
        "// Generated by scripts/export-analysis.py; edit the Python M2 models.",
        "import type { CanonicalId, DecimalString, DateString } from '../contracts/generated'",
    ]
    for name in sorted(schema["$defs"]):
        lines.append(f"export type {name} = {emit(schema['$defs'][name])};")
    return {
        ROOT / "frontend/src/analysis/schema.json": (
            json.dumps(schema, indent=2, sort_keys=True) + "\n"
        ).encode(),
        ROOT / "frontend/src/analysis/generated.ts": ("\n".join(lines) + "\n").encode(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    for path, content in artifacts().items():
        if options.check:
            if not path.is_file() or path.read_bytes() != content:
                print("M2 schema/types differ; run scripts/export-analysis.py.")
                return 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print("M2 schema/types match." if options.check else "M2 schema/types generated.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
